/** Template values accepted by the interpolator. */
export type TranslateValues = Record<string, string | number>

/** Interpolate {name} placeholders in one dictionary entry. */
export function interpolate(template: string, values?: TranslateValues): string {
  if (values === undefined) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name]
    return value === undefined ? match : String(value)
  })
}

/** Active dictionary, picked by the document language at call time. */
export function dictionary(): Record<UsageKey, string> {
  const lang = typeof document !== 'undefined' ? document.documentElement.lang : 'zh'
  return lang.toLowerCase().startsWith('en') ? { ...en } : { ...zh }
}

/** Translate a key with optional {name} template params (current language). */
export function tt(key: UsageKey, values?: TranslateValues): string {
  return interpolate(dictionary()[key], values)
}
